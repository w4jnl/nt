// Workspace is the app's state: the repository nt works on, its index, the note on screen, the
// sync state. Files are read here; everything that writes goes through nt, the note's text
// through its editor (NoteEditor).
import Foundation
import Observation
#if os(macOS)
import AppKit
#else
import UIKit
#endif

@MainActor
@Observable
final class Workspace {
    enum Phase: Equatable {
        case loading
        case ready
        case problem(String)
    }

    enum Selection: Hashable {
        case today
        case todos
        case calendar
        case weekly
        case agents
        case note(String)
        case folder(String) // a folder in the sidebar: where a new note goes; the note stays
    }

    /// Ask is a question put to the person before nt writes: a name for a new note or folder,
    /// or a new name; the folder to move to; whether to delete.
    enum Ask: Identifiable, Equatable {
        case newNote(String) // in this folder; "" is nt's default folder
        case newFolder(String) // in this folder; "" is the root
        case rename(String)
        case move(String)
        case delete(String)

        var id: String { "\(self)" }
    }

    /// Removal is what nt rm deletes, or would: nt rm --json.
    struct Removal: Decodable, Equatable, Sendable {
        let rel: String
        let folder: Bool
        var title: String?
        var images: [String]?
        let links: Int
    }

    /// Plan is what a move or a rename did: nt mv --json, nt rename --json.
    struct Plan: Decodable, Equatable, Sendable {
        let from: String
        let to: String
        let folder: Bool
    }

    enum PaletteMode: Equatable {
        case open // titles, then text, then a new note
        case text // text only
        case new // a new note's title (⌘N)
    }

    struct Backlink: Equatable, Sendable {
        let path: String
        let title: String
        let folder: String
    }

    /// The note on screen: sha is the SHA-256 of the file as the editor last read or saved it.
    /// Digests are regenerated by nt, so they are shown read-only.
    struct OpenNote: Equatable {
        let path: String
        var sha: String
        var readOnly: Bool
        var backlinks: [Backlink]
    }

    struct SearchHit: Decodable, Hashable, Sendable {
        let path: String
        let line: Int
        let text: String
    }

    var phase: Phase = .loading
    var index: RepoIndex?
    var tree = SidebarTree()
    var selection: Selection?
    var note: OpenNote?
    var todayPath = ""
    var status: SyncStatus?
    var syncing = false
    var palette: PaletteMode?
    var sidebar = true // shown; the split view's toggle and View > Hide Sidebar change it
    var focusMode = false
    var todos: [Todo] = [] // every todo, open ones overdue first, as nt todo --all lists them
    var journalDays: Set<String> = [] // the days that have a journal, YYYY-MM-DD
    var calendarDay = "" // the day the calendar shows; "" for today
    var flash = "" // one line for the person: what went wrong, or where a link pointed
    var words = 0
    var editing = false // the note has the keyboard: the iPhone and iPad show the keyboard bar
    var undoable = false // the note has something to undo, or to redo, for the keyboard bar
    var redoable = false
    var expanded: Set<String> = Set(UserDefaults.standard.stringArray(forKey: "expandedFolders") ?? []) {
        didSet { UserDefaults.standard.set(Array(expanded), forKey: "expandedFolders") }
    }
    var recent: [String] = UserDefaults.standard.stringArray(forKey: "recentNotes") ?? [] { // the notes opened last, newest first
        didSet { UserDefaults.standard.set(recent, forKey: "recentNotes") }
    }
    var textSize = TextSize(rawValue: UserDefaults.standard.double(forKey: "textSize")) ?? .standard {
        didSet {
            UserDefaults.standard.set(textSize.rawValue, forKey: "textSize")
            editor?.zoom(textSize.rawValue)
        }
    }
    var active = true // the app is in front; the menu bar's alert mark blinks only while it is not
    var settings: [ConfigSetting] = [] // nt config, for Settings
    var settingsProblem = ""
    var ask: Ask? // a question before nt writes, shown by Asking
    #if !os(macOS)
    var preview: URL? // a file a link points at, shown with Quick Look
    var picking = false // the keyboard bar asked for a photo
    #endif

    /// navigate shows a note the person asked for on the iPhone: a screen of its own on the
    /// stack, so Back returns. Unset, on the Mac and the iPad, the note opens in place.
    @ObservationIgnored var navigate: ((_ path: String, _ anchor: String, _ line: Int, _ end: Bool) -> Void)?
    /// relocated and removed keep the iPhone's screens on what they showed after a move, a
    /// rename or a delete: a screen follows its note or folder, or goes with it.
    @ObservationIgnored var relocated: ((_ from: String, _ to: String) -> Void)?
    @ObservationIgnored var removed: ((_ path: String) -> Void)?

    @ObservationIgnored let nt: NT?
    @ObservationIgnored private(set) var editor: NoteEditor?
    #if os(macOS)
    @ObservationIgnored private var watcher: RepoWatcher?
    #endif
    @ObservationIgnored private var reindexTask: Task<Void, Never>?
    @ObservationIgnored private var flashTask: Task<Void, Never>?
    @ObservationIgnored private var sidebarBeforeFocus = true
    @ObservationIgnored private var reportCache: [String: [AgentReport]] = [:]
    @ObservationIgnored private var quitting = false
    @ObservationIgnored private var opening = 0 // counts opens, so the last one asked for wins
    #if !os(macOS)
    @ObservationIgnored private var syncSoon: Task<Void, Never>?
    #endif

    #if os(macOS)
    init(nt: NT? = NT.locate()) {
        self.nt = nt
    }
    #else
    init(nt: NT?) {
        self.nt = nt
    }
    #endif

    var root: URL? { index.map { URL(filePath: $0.root) } }

    /// start finds the repository and, on the Mac, opens today; on iPhone and iPad the layout
    /// opens a note (the iPad today, the iPhone none until one is asked for). Under tests it does
    /// nothing: the app must not touch the person's notes there.
    func start() async {
        if ProcessInfo.processInfo.environment["XCTestConfigurationFilePath"] != nil || phase == .ready { return }
        guard await prepare() else { return }
        watch()
        #if os(macOS)
        await openToday()
        #endif
        // For screenshots: -NTOpen <repository path> opens a note after today, -NTView todos,
        // calendar, weekly or agents a view, -NTPalette open, text or new the palette (and
        // -NTQuery types into it).
        if let path = UserDefaults.standard.string(forKey: "NTOpen") { await open(path) }
        switch UserDefaults.standard.string(forKey: "NTView") {
        case "todos": select(.todos)
        case "calendar": select(.calendar)
        case "weekly": select(.weekly)
        case "agents": select(.agents)
        default: break
        }
        switch UserDefaults.standard.string(forKey: "NTPalette") {
        case "open": palette = .open
        case "text": palette = .text
        case "new": palette = .new
        default: break
        }
    }

    /// prepare reads the repository's index and makes the editor; false, with the problem on
    /// screen, when nt cannot.
    func prepare() async -> Bool {
        guard let nt else {
            phase = .problem("nt is not installed. Install it with brew install w4jnl/tap/nt, or set NT_BIN to its path.")
            return false
        }
        do {
            try await reindex(nt)
        } catch {
            phase = .problem(error.localizedDescription)
            return false
        }
        if editor == nil {
            editor = NoteEditor(workspace: self)
            editor?.zoom(textSize.rawValue)
        }
        phase = .ready
        return true
    }

    func reindex(_ nt: NT) async throws {
        let ix = try await nt.json(RepoIndex.self, ["_editor", "index"])
        index = ix
        tree = SidebarTree.build(ix, thisYear: String(ix.day.prefix(4)))
        status = SyncStatus.read(stateDir: ix.state)
        reportCache = [:]
        journalDays = Set(ix.notes.compactMap { n -> String? in
            guard n.path.hasPrefix(ix.folders.daily + "/") else { return nil }
            let name = (n.path as NSString).lastPathComponent
            return name.wholeMatch(of: /\d{4}-\d{2}-\d{2}\.md/) != nil ? String(name.prefix(10)) : nil
        })
        await loadTodos()
        if let n = note {
            let back = backlinks(n.path)
            if back != n.backlinks {
                note?.backlinks = back
                editor?.setBacklinks(back)
            }
        }
    }

    // MARK: Opening notes

    func select(_ sel: Selection?) {
        guard let sel, sel != selection else { return }
        switch sel {
        case .today: Task { await openToday() }
        case .weekly: Task { await openWeekly() }
        case .note(let path): show(path)
        case .folder: selection = sel
        case .todos, .calendar, .agents:
            Task {
                await editor?.save()
                selection = sel
            }
        }
    }

    /// weeklyPath is the newest weekly digest, which Weekly opens.
    var weeklyPath: String? {
        index.flatMap { Agenda.latestWeekly($0.notes.map(\.path), folder: $0.folders.weekly) }
    }

    /// openWeekly opens the newest weekly digest, read-only; without one, Weekly says how one
    /// is made.
    func openWeekly() async {
        guard let path = weeklyPath else {
            await editor?.save()
            selection = .weekly
            return
        }
        await open(path)
    }

    private func selectionFor(_ path: String) -> Selection {
        path == todayPath ? .today : path == weeklyPath ? .weekly : .note(path)
    }

    func openToday() async {
        if let p = await todayNote() { show(p) }
    }

    /// goToday goes to today's journal, as a note the person asked for.
    func goToday() async {
        if let p = await todayNote() { go(p) }
    }

    /// todayNote is today's journal, which nt makes when it is not there yet.
    private func todayNote() async -> String? {
        guard let nt else { return nil }
        struct Today: Decodable { let rel: String }
        do {
            todayPath = try await nt.json(Today.self, ["t", "--json"]).rel
            return todayPath
        } catch {
            say(error.localizedDescription)
            return nil
        }
    }

    /// show puts the note at path on screen, scrolled to a heading's anchor or to a line; end
    /// puts the cursor at its end, for a note just made. The note on screen is saved first.
    func show(_ path: String, anchor: String = "", line: Int = 0, end: Bool = false, reload: Bool = false) {
        Task { await open(path, anchor: anchor, line: line, end: end, reload: reload) }
    }

    /// go shows a note the person asked for: a link followed, a todo's note, a day's journal.
    func go(_ path: String, anchor: String = "", line: Int = 0) {
        if let navigate { navigate(path, anchor, line, false) } else { show(path, anchor: anchor, line: line) }
    }

    func open(_ path: String, anchor: String = "", line: Int = 0, end: Bool = false, reload: Bool = false) async {
        guard let root, let editor else { return }
        opening += 1
        let mine = opening
        if path == note?.path, !reload {
            if !anchor.isEmpty { editor.scroll(to: anchor) } else if line > 0 { editor.go(to: line) }
            selection = selectionFor(path)
            return
        }
        guard await editor.save() else {
            say("\(title(note?.path ?? path)) is not saved, so it stays open")
            return
        }
        guard mine == opening else { return } // another note was asked for while this one waited
        let url = root.appending(path: path)
        guard let data = try? Data(contentsOf: url), let text = String(data: data, encoding: .utf8) else {
            say("\(path) cannot be read: is it still there?")
            return
        }
        let n = OpenNote(path: path, sha: sha256(data), readOnly: Self.readOnly(text), backlinks: backlinks(path))
        note = n
        editor.load(n, text: text, anchor: anchor, line: line, end: end)
        selection = selectionFor(path)
        recent = Self.remember(path, in: recent)
        for dir in SidebarTree.ancestors(path) where !expanded.contains(dir) {
            expanded.insert(dir)
        }
    }

    /// readOnly says whether a note is a digest, the day's or the week's, which nt writes again
    /// whenever it changes, so an edit would not last.
    nonisolated static func readOnly(_ text: String) -> Bool {
        guard text.hasPrefix("---\n") || text.hasPrefix("---\r\n") else { return false }
        for line in text.split(separator: "\n", omittingEmptySubsequences: false).dropFirst() {
            let l = line.trimmingCharacters(in: .whitespaces)
            if l == "---" { break }
            if l == "type: digest" || l == "type: weekly" { return true }
        }
        return false
    }

    /// saved: the editor's text for path is on disk, as sha.
    func saved(_ path: String, sha: String) {
        if note?.path == path { note?.sha = sha }
    }

    func title(_ path: String) -> String {
        index?.title(path) ?? (path as NSString).lastPathComponent
    }

    /// day is the day as nt counts it (day_starts), for a todo's done: date.
    func day() async -> String {
        if let nt, let out = try? await nt.run(["_editor", "day"]), out.status == 0 {
            let d = String(decoding: out.stdout, as: UTF8.self).trimmingCharacters(in: .whitespacesAndNewlines)
            if !d.isEmpty { return d }
        }
        return index?.day ?? ""
    }

    func backlinks(_ path: String) -> [Backlink] {
        guard let ix = index else { return [] }
        return (ix.back[path] ?? []).map { from in
            let dir = (from as NSString).deletingLastPathComponent
            return Backlink(path: from, title: ix.title(from), folder: dir.isEmpty ? "/" : dir)
        }
    }

    /// follow follows a link the person clicked in the note on screen.
    func follow(_ href: String) {
        guard let n = note, let root else { return }
        let target = Links.target(from: n.path, href) { FileManager.default.fileExists(atPath: root.appending(path: $0).path) }
        switch target {
        case .note(let path, let anchor):
            if path == n.path, !anchor.isEmpty {
                scroll(to: anchor)
            } else {
                go(path, anchor: anchor)
            }
        case .anchor(let a): scroll(to: a)
        #if os(macOS)
        case .file(let path): NSWorkspace.shared.open(root.appending(path: path))
        case .web(let url): NSWorkspace.shared.open(url)
        #else
        case .file(let path): preview = root.appending(path: path)
        case .web(let url): UIApplication.shared.open(url)
        #endif
        case .missing(let path): say("\(path) is not in the repository")
        case .invalid: say("\(href) is not a link nt can follow")
        }
    }

    func scroll(to anchor: String) {
        editor?.scroll(to: anchor)
    }

    // MARK: Todos, agents and journals

    func loadTodos() async {
        guard let nt, let list = try? await nt.json(Todo.List.self, ["todo", "--all", "--json"]) else { return }
        if list.todos != todos { todos = list.todos }
    }

    /// toggle checks a todo, adding done:, or opens it again, through nt.
    func toggle(_ t: Todo) async {
        await setDone(t, !t.done)
    }

    /// setDone checks a todo (done) or opens it again, through nt.
    func setDone(_ t: Todo, _ done: Bool) async {
        await todo([done ? "done" : "undo", t.id])
    }

    /// setDue sets a todo's due date from words: fri, +3d, 2026-11-03; none clears it.
    func setDue(_ t: Todo, _ when: String) async {
        await todo(["due", t.id, when])
    }

    /// addTodo adds a todo to the root's todo.md; due:fri in the text sets its due date.
    func addTodo(_ text: String) async -> Bool {
        await todo(["add", "--", text])
    }

    #if !os(macOS)
    /// wrote: nt wrote to the clone (a todo ticked or added, a line captured). The app reads the
    /// notes again, the note on screen too, and half a minute later a sync follows, as after a
    /// save; the Mac has its watcher and nt's sync timer for this.
    func wrote() async {
        if let nt { try? await reindex(nt) }
        await reloadIfChanged()
        syncSoon?.cancel()
        syncSoon = Task {
            try? await Task.sleep(for: .seconds(30))
            guard !Task.isCancelled else { return }
            await syncNow()
        }
    }
    #endif

    @discardableResult
    private func todo(_ args: [String]) async -> Bool {
        guard let nt else { return false }
        await editor?.save() // the note on screen may hold the todo
        var ok = false
        do {
            let out = try await nt.run(["todo"] + args + ["--json"])
            ok = out.status == 0
            if !ok { say(NTError.message(out.stderr)) }
            #if !os(macOS)
            if ok { await wrote() }
            #endif
        } catch {
            say(error.localizedDescription)
        }
        await loadTodos()
        return ok
    }

    /// reports are a day's agent reports, read from their frontmatter, the latest session first.
    func reports(on day: String) -> [AgentReport] {
        if let r = reportCache[day] { return r }
        guard let root, let ix = index, let p = Agenda.parts(day) else { return [] }
        let dir = "\(ix.folders.agents)/\(String(format: "%04d", p.year))/\(day)"
        let names = (try? FileManager.default.contentsOfDirectory(atPath: root.appending(path: dir).path)) ?? []
        var out: [AgentReport] = []
        for name in names where name.hasSuffix(".md") && name != "README.md" && !name.hasPrefix(".") && !name.contains(".conflict-") {
            let rel = dir + "/" + name
            guard let text = try? String(contentsOf: root.appending(path: rel), encoding: .utf8),
                  let r = AgentReport.parse(text, path: rel) else { continue }
            out.append(r)
        }
        let began = Dictionary(out.map { ($0.path, Agenda.instant($0.created) ?? .distantPast) }, uniquingKeysWith: { a, _ in a })
        out.sort { a, b in
            let da = began[a.path] ?? .distantPast, db = began[b.path] ?? .distantPast
            return da != db ? da > db : a.path > b.path
        }
        reportCache[day] = out
        return out
    }

    /// agentDays are the days with agent reports, newest first.
    var agentDays: [String] {
        guard let ix = index else { return [] }
        return Agenda.agentDays(ix.dirs, folder: ix.folders.agents)
    }

    /// journalPath is where the journal of a day is, whether or not it exists.
    func journalPath(_ day: String) -> String {
        "\(index?.folders.daily ?? "daily")/\(day.prefix(4))/\(day).md"
    }

    /// log is the ## Log of a day's journal.
    func log(of day: String) -> [LogLine] {
        guard journalDays.contains(day), let root,
              let text = try? String(contentsOf: root.appending(path: journalPath(day)), encoding: .utf8) else { return [] }
        return Agenda.log(text)
    }

    var today: String { index?.day ?? "" }

    // MARK: Writing

    /// newFolder is where ⌘N puts a note: the folder selected in the sidebar, else the folder of
    /// the note on screen, unless that is the journals', the agents' or the weekly folder or the
    /// root; then nt's default folder ("").
    var newFolder: String {
        if case .folder(let f) = selection { return f }
        guard let n = note, let ix = index else { return "" }
        return Self.newFolder(for: n.path, folders: ix.folders)
    }

    nonisolated static func newFolder(for path: String, folders: RepoIndex.Folders) -> String {
        let dir = (path as NSString).deletingLastPathComponent
        let kept = [folders.daily, folders.agents, folders.weekly].filter { !$0.isEmpty }
        if dir.isEmpty || kept.contains(where: { dir == $0 || dir.hasPrefix($0 + "/") }) { return "" }
        return dir
    }

    /// create makes a note titled title in folder with nt n and opens it, the cursor at its end.
    func create(_ title: String, in folder: String) async {
        guard let nt else { return }
        struct Created: Decodable { let rel: String }
        do {
            var args = ["n", "--json", "--", title.trimmingCharacters(in: .whitespaces)]
            if !folder.isEmpty { args.append(folder) }
            let c = try await nt.json(Created.self, args)
            await afterWrite()
            if let navigate { navigate(c.rel, "", 0, true) } else { await open(c.rel, end: true) }
        } catch {
            say(error.localizedDescription)
        }
    }

    // MARK: Notes and folders

    /// fixed says whether nt keeps path where it is: the journals, the agents' reports and the
    /// weekly digests, and their folders (docs/format.md §13).
    func fixed(_ path: String) -> Bool {
        guard let f = index?.folders else { return true }
        return [f.daily, f.agents, f.weekly].contains { !$0.isEmpty && (path == $0 || path.hasPrefix($0 + "/")) }
    }

    /// deletable says whether path may be deleted: anything but the root and the journals', the
    /// agents' and the weekly folder themselves.
    func deletable(_ path: String) -> Bool {
        guard let f = index?.folders, !path.isEmpty else { return false }
        return ![f.daily, f.agents, f.weekly].contains(path)
    }

    /// makeFolder makes a folder in parent ("" the root) with nt mkdir, and selects it.
    @discardableResult
    func makeFolder(_ name: String, in parent: String) async -> Bool {
        let n = name.trimmingCharacters(in: .whitespaces)
        guard let nt, !n.isEmpty else { return false }
        struct Made: Decodable { let rel: String }
        do {
            let m = try await nt.json(Made.self, ["mkdir", "--json", parent.isEmpty ? n : parent + "/" + n])
            await afterWrite()
            if !parent.isEmpty { expanded.insert(parent) }
            if navigate == nil { selection = .folder(m.rel) }
            return true
        } catch {
            say(error.localizedDescription)
            return false
        }
    }

    /// rename gives a note a new title, and the file name that goes with it, or a folder a new
    /// name, with nt rename, which fixes the links to it.
    @discardableResult
    func rename(_ path: String, to name: String) async -> Bool {
        await relocate(["rename", "--json", "--", path, name.trimmingCharacters(in: .whitespaces)])
    }

    /// move moves a note or a folder into folder ("" the root) with nt mv, which fixes the links.
    @discardableResult
    func move(_ path: String, to folder: String) async -> Bool {
        await relocate(["mv", "--json", "--", path, folder.isEmpty ? "/" : folder + "/"])
    }

    private func relocate(_ args: [String]) async -> Bool {
        guard let nt else { return false }
        guard await editor?.save() ?? true else {
            say("\(title(note?.path ?? "")) is not saved, so nothing moves")
            return false
        }
        do {
            let p = try await nt.json(Plan.self, args)
            func new(_ q: String) -> String {
                q == p.from ? p.to : q.hasPrefix(p.from + "/") ? p.to + q.dropFirst(p.from.count) : q
            }
            await afterWrite()
            expanded = Set(expanded.map(new))
            recent = recent.map(new)
            if case .folder(let f) = selection { selection = .folder(new(f)) }
            relocated?(p.from, p.to)
            if let n = note, new(n.path) != n.path { await open(new(n.path), reload: true) }
            return true
        } catch {
            say(error.localizedDescription)
            return false
        }
    }

    /// removal is what deleting path takes with it, and how many notes link to it, for the
    /// question before it.
    func removal(_ path: String) async -> Removal? {
        guard let nt else { return nil }
        do {
            return try await nt.json(Removal.self, ["rm", "--dry-run", "--json", "--", path])
        } catch {
            say(error.localizedDescription)
            return nil
        }
    }

    /// remove deletes a note, with the images only it uses, or an empty folder, with nt rm; git
    /// keeps them.
    @discardableResult
    func remove(_ path: String) async -> Bool {
        guard let nt else { return false }
        guard await editor?.save() ?? true else {
            say("\(title(note?.path ?? "")) is not saved, so nothing is deleted")
            return false
        }
        do {
            let r = try await nt.json(Removal.self, ["rm", "--json", "--", path])
            await afterWrite()
            removed?(path)
            if selection == .folder(path) || selection == .note(path) { selection = nil }
            if let n = note, n.path == path || n.path.hasPrefix(path + "/") {
                note = nil
                if navigate == nil { await openToday() }
            }
            say("Deleted " + (r.title ?? r.rel))
            return true
        } catch {
            say(error.localizedDescription)
            return false
        }
    }

    /// afterWrite reads the notes again after nt wrote: the Mac's watcher would, a moment later;
    /// the phone also syncs half a minute later.
    private func afterWrite() async {
        #if os(macOS)
        if let nt { try? await reindex(nt) }
        #else
        await wrote()
        #endif
    }

    /// toggleFocus turns focus mode on or off: the sidebar goes and the other paragraphs dim.
    func toggleFocus() {
        focusMode.toggle()
        if focusMode {
            sidebarBeforeFocus = sidebar
            sidebar = false
        } else {
            sidebar = sidebarBeforeFocus
        }
        editor?.focusMode(focusMode)
        if focusMode { editor?.focus() }
    }

    /// settle saves the note and syncs what was saved: the person left the app. The phone syncs
    /// whether or not anything was written, to leave the clone as the remote has it.
    func settle() async {
        guard let editor else { return }
        await editor.save()
        #if os(macOS)
        editor.kick()
        #else
        syncSoon?.cancel()
        while syncing { try? await Task.sleep(for: .milliseconds(200)) }
        await syncNow()
        #endif
    }

    /// finish saves the note before the app quits, and says whether it may. When nt cannot save
    /// it, the app stays, once: a second Quit leaves without it.
    func finish() async -> Bool {
        guard let editor else { return true }
        if await editor.save() {
            editor.kick()
            return true
        }
        if quitting { return true }
        quitting = true
        say("\(title(note?.path ?? "")) is not saved. Quit again to leave without it.")
        return false
    }

    var unsaved: Bool { editor?.dirty ?? false }

    /// broken are the link destinations of the note on screen that point at nothing.
    func broken(_ dests: [String]) -> [String] {
        guard let n = note, let root else { return [] }
        return dests.filter { d in
            guard let p = Links.resolve(from: n.path, d) else { return false }
            return !FileManager.default.fileExists(atPath: root.appending(path: p).path)
        }
    }

    // MARK: Search

    func search(_ query: String) async -> [SearchHit] {
        guard let nt, !query.trimmingCharacters(in: .whitespaces).isEmpty else { return [] }
        guard let out = try? await nt.run(["s", "--json", query]), out.status == 0 else { return [] }
        return (try? JSONDecoder().decode([SearchHit].self, from: out.stdout)) ?? []
    }

    /// remember puts path first among the notes opened last, at most max of them.
    nonisolated static func remember(_ path: String, in list: [String], max: Int = 8) -> [String] {
        Array(([path] + list.filter { $0 != path }).prefix(max))
    }

    /// recentNotes are the notes opened last that are still there, newest first.
    func recentNotes(_ n: Int) -> [String] {
        guard let ix = index else { return [] }
        let have = Set(ix.notes.map(\.path))
        return Array(recent.filter { have.contains($0) }.prefix(n))
    }

    // MARK: Settings

    /// loadSettings reads nt config, this Mac's settings and every machine's.
    func loadSettings() async {
        guard let nt else { return }
        do {
            settings = try await nt.json(ConfigSetting.List.self, ["config", "--json"]).settings
            settingsProblem = ""
        } catch {
            settingsProblem = error.localizedDescription
        }
    }

    /// setSetting changes one setting through nt config set, which checks it; it returns nt's
    /// complaint when it would not take the value, else nil, and does what the change needs.
    func setSetting(_ s: ConfigSetting, to value: String) async -> String? {
        guard let nt else { return "nt is not installed" }
        do {
            let out = try await nt.run(["config", "set", s.key, value])
            if out.status != 0 { return NTError.message(out.stderr) }
        } catch {
            return error.localizedDescription
        }
        await loadSettings()
        switch ConfigSetting.effect(of: s.key) {
        case .none: break
        case .reindex: try? await reindex(nt)
        case .restart: await restart()
        }
        return nil
    }

    /// restart starts over on the repository nt names now, after repo changed.
    func restart() async {
        guard await editor?.save() ?? true else { return }
        #if os(macOS)
        watcher = nil
        #endif
        note = nil
        selection = nil
        guard await prepare() else { return }
        watch()
        await openToday()
    }

    // MARK: Sync

    /// needsYou says sync needs the person: a conflict or an error. Offline is not one.
    var needsYou: Bool { status?.state == "conflict" || status?.state == "error" }

    func syncNow() async {
        guard let nt, !syncing else { return }
        syncing = true
        let out = try? await nt.run(["sync", "--json"])
        syncing = false
        if let ix = index { status = SyncStatus.read(stateDir: ix.state) }
        if let out, out.status != 0 { say(NTError.message(out.stderr)) }
        #if !os(macOS)
        // no watcher on the phone: what the sync merged is read here
        try? await reindex(nt)
        await reloadIfChanged()
        #endif
    }

    // MARK: Changes on disk

    #if os(macOS)
    private func watch() {
        guard let ix = index else { return }
        let root = ix.root, state = ix.state
        watcher = RepoWatcher(paths: [root, state]) { [weak self] paths in
            Task { @MainActor in self?.changed(paths, root: root, state: state) }
        }
    }

    private func changed(_ paths: [String], root: String, state: String) {
        if paths.contains(where: { $0.hasPrefix(state + "/") }) {
            status = SyncStatus.read(stateDir: state)
        }
        guard paths.contains(where: { RepoWatcher.relevant($0, root: root) }) else { return }
        reindexTask?.cancel()
        reindexTask = Task {
            try? await Task.sleep(for: .milliseconds(250))
            guard !Task.isCancelled, let nt else { return }
            try? await reindex(nt)
            await reloadIfChanged()
        }
    }
    #else
    /// watch: nothing else writes the clone on the phone, so the app reindexes after its own
    /// writes and syncs instead.
    private func watch() {}
    #endif

    /// reloadIfChanged hands the editor the note on screen as another writer left it on disk.
    func reloadIfChanged() async {
        guard let n = note, let root, let editor else { return }
        guard let data = try? Data(contentsOf: root.appending(path: n.path)) else {
            say("\(n.path) was moved or deleted")
            return
        }
        let sha = sha256(data)
        guard sha != n.sha, let text = String(data: data, encoding: .utf8) else { return }
        if await editor.external(text) { saved(n.path, sha: sha) }
    }

    // MARK: Messages

    func say(_ msg: String) {
        flash = msg
        flashTask?.cancel()
        flashTask = Task {
            try? await Task.sleep(for: .seconds(4))
            if !Task.isCancelled { flash = "" }
        }
    }
}
