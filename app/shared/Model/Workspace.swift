// Workspace is the app's state: the repository nt works on, its index, the note on screen, the
// sync state. Files are read here; everything that writes goes through nt, the note's text
// through its editor (NoteEditor).
import Foundation
import Observation
#if os(macOS)
import AppKit
#else
import UIKit
#endif

@MainActor
@Observable
final class Workspace {
    enum Phase: Equatable {
        case loading
        case ready
        case problem(String)
    }

    enum Selection: Hashable {
        case today
        case todos
        case calendar
        case weekly
        case agents
        case note(String)
        case folder(String) // a folder in the sidebar: where a new note goes; the note stays
    }

    /// Ask is a question put to the person before nt writes: a name for a new note or folder,
    /// or a new name; the folder to move to; whether to delete.
    enum Ask: Identifiable, Equatable {
        case newNote(String) // in this folder; "" is nt's default folder
        case newFolder(String) // in this folder; "" is the root
        case newTodo(String) // at the end of Inbox in this folder's todo.md
        case rename(String)
        case move(String)
        case delete(String)

        var id: String { "\(self)" }
    }

    /// Removal is what nt rm deletes, or would: nt rm --json.
    struct Removal: Decodable, Equatable, Sendable {
        let rel: String
        let folder: Bool
        var title: String?
        var images: [String]?
        let links: Int
    }

    /// Plan is what a move or a rename did: nt mv --json, nt rename --json.
    struct Plan: Decodable, Equatable, Sendable {
        let from: String
        let to: String
        let folder: Bool
    }

    enum PaletteMode: Equatable {
        case open // titles, then text, then a new note
        case text // text only
        case new // a new note's title (⌘N)
    }

    struct Backlink: Equatable, Sendable {
        let path: String
        let title: String
        let folder: String
    }

    /// The note on screen: sha is the SHA-256 of the file as the editor last read or saved it.
    /// Digests are regenerated by nt, so they are shown read-only.
    struct OpenNote: Equatable {
        let path: String
        var sha: String
        var readOnly: Bool
        var backlinks: [Backlink]
    }

    struct SearchHit: Decodable, Hashable, Sendable {
        let path: String
        let line: Int
        let text: String
    }

    var phase: Phase = .loading
    var index: RepoIndex?
    var tree = SidebarTree()
    var selection: Selection?
    var note: OpenNote?
    var todayPath = ""
    var status: SyncStatus?
    var syncing = false
    var palette: PaletteMode?
    var searchAsked: String? // a search a note asked for, a tag in its frontmatter, for the search field to take
    var todoSearch = false // Search asked while Todos is shown: its field takes the keys, then sets this back
    var sidebar = true // shown; the split view's toggle and View > Hide Sidebar change it
    var focusMode = false
    var todos: [Todo] = [] // every todo, open ones overdue first, as nt todo --all lists them
    var journalDays: Set<String> = [] // the days that have a journal, YYYY-MM-DD
    var calendarDay = "" // the day the calendar shows; "" for today
    var flash = "" // one line for the person: what went wrong, or where a link pointed
    var words = 0
    // Find in the note on screen (FindBar): the words typed are marked as a search's are, and
    // the page says which hit the cursor is on of how many.
    var finding = false
    var findText = ""
    var findAt = 0
    var findOf = 0
    var findFocus = 0 // bumped to give the bar's field the keyboard again (⌘F while it is open)
    var editing = false // the note has the keyboard: the iPhone and iPad show the keyboard bar
    var undoable = false // the note has something to undo, or to redo, for the keyboard bar
    var redoable = false
    var expanded: Set<String> = Set(UserDefaults.standard.stringArray(forKey: "expandedFolders") ?? []) {
        didSet { UserDefaults.standard.set(Array(expanded), forKey: "expandedFolders") }
    }
    var recent: [String] = UserDefaults.standard.stringArray(forKey: "recentNotes") ?? [] { // the notes opened last, newest first
        didSet { UserDefaults.standard.set(recent, forKey: "recentNotes") }
    }
    /// history is the notes links were followed from, the last at the end, so Back returns to
    /// them scrolled as they were, as the terminal browser's b does. The iPhone's stack keeps
    /// its own; this is the Mac's and the iPad's.
    var history: [Visit] = []
    nonisolated static let historyMax = 50
    var canGoBack: Bool { !history.isEmpty }

    /// Visit is a note a link was followed from and how far it was scrolled.
    struct Visit: Equatable, Sendable {
        let path: String
        let top: Double

        /// moved is the visit after from moved to to: a note in what moved follows it.
        func moved(_ from: String, _ to: String) -> Visit {
            path == from ? Visit(path: to, top: top) : path.hasPrefix(from + "/") ? Visit(path: to + path.dropFirst(from.count), top: top) : self
        }

        /// names says whether the visit is path or something in it.
        func names(_ path: String) -> Bool { self.path == path || self.path.hasPrefix(path + "/") }
    }
    var textSize = TextSize(rawValue: UserDefaults.standard.double(forKey: "textSize")) ?? .standard {
        didSet {
            UserDefaults.standard.set(textSize.rawValue, forKey: "textSize")
            editor?.zoom(textSize.rawValue)
        }
    }
    var active = true // the app is in front; the menu bar's alert mark blinks only while it is not
    var settings: [ConfigSetting] = [] // nt config, for Settings
    var settingsProblem = ""
    var ask: Ask? // a question before nt writes, shown by Asking
    #if !os(macOS)
    var preview: URL? // a file a link points at, shown with Quick Look
    var picking = false // the keyboard bar asked for a photo
    @ObservationIgnored let dictation = Listener() // the keyboard bar's mic
    #endif

    /// navigate shows a note the person asked for on the iPhone: a screen of its own on the
    /// stack, so Back returns. Unset, on the Mac and the iPad, the note opens in place.
    @ObservationIgnored var navigate: ((_ path: String, _ anchor: String, _ line: Int, _ end: Bool, _ find: String) -> Void)?
    /// relocated and removed keep the iPhone's screens on what they showed after a move, a
    /// rename or a delete: a screen follows its note or folder, or goes with it.
    @ObservationIgnored var relocated: ((_ from: String, _ to: String) -> Void)?
    @ObservationIgnored var removed: ((_ path: String) -> Void)?
    /// home closes the iPhone's screens down to the home list.
    @ObservationIgnored var home: (() -> Void)?

    @ObservationIgnored let nt: NT?
    @ObservationIgnored private(set) var editor: NoteEditor?
    #if os(macOS)
    @ObservationIgnored private var watcher: RepoWatcher?
    #endif
    @ObservationIgnored private var reindexTask: Task<Void, Never>?
    @ObservationIgnored private var flashTask: Task<Void, Never>?
    @ObservationIgnored private var sidebarBeforeFocus = true
    @ObservationIgnored private var reportCache: [String: [AgentReport]] = [:]
    @ObservationIgnored private var quitting = false
    @ObservationIgnored private var opening = 0 // counts opens, so the last one asked for wins
    @ObservationIgnored private var askedFile: URL? // a file asked for before the repository was ready
    @ObservationIgnored private var starting = false
    @ObservationIgnored private var sidebarBeforeOutside = true
    @ObservationIgnored private var outsideTitle = ""
    #if !os(macOS)
    @ObservationIgnored private var syncSoon: Task<Void, Never>?
    #endif

    #if os(macOS)
    init(nt: NT? = NT.locate()) {
        self.nt = nt
    }
    #else
    init(nt: NT?) {
        self.nt = nt
    }
    #endif

    var root: URL? { index.map { URL(filePath: $0.root) } }

    /// outside says the note on screen is a markdown file outside the repository, opened from
    /// Finder (openFile): its path is the file's full path, not a repository path.
    var outside: Bool { note?.path.hasPrefix("/") ?? false }

    /// file is where a note's path is on disk: in the repository, or anywhere for a file outside it.
    func file(_ path: String) -> URL? { Self.fileURL(path, root: root) }

    nonisolated static func fileURL(_ path: String, root: URL?) -> URL? {
        path.hasPrefix("/") ? URL(filePath: path) : root?.appending(path: path)
    }

    /// start finds the repository and, on the Mac, opens today, or the note a file asked for
    /// (openFile); on iPhone and iPad the layout opens a note (the iPad today, the iPhone none
    /// until one is asked for). Under tests it does nothing: the app must not touch the person's
    /// notes there. The window's task can run it twice at launch; the second call returns.
    func start() async {
        if ProcessInfo.processInfo.environment["XCTestConfigurationFilePath"] != nil || phase == .ready || starting { return }
        starting = true
        defer { starting = false }
        guard await prepare() else { return }
        watch()
        // For screenshots: -NTOpen <repository path> opens a note in place of today, -NTView
        // todos, calendar, weekly or agents a view, -NTPalette open, text or new the palette
        // (and -NTQuery types into it).
        if let path = UserDefaults.standard.string(forKey: "NTOpen") {
            await open(path)
        } else if let file = askedFile {
            askedFile = nil
            await openFile(file)
        } else {
            #if os(macOS)
            await openToday()
            #endif
        }
        switch UserDefaults.standard.string(forKey: "NTView") {
        case "todos": select(.todos)
        case "calendar": select(.calendar)
        case "weekly": select(.weekly)
        case "agents": select(.agents)
        default: break
        }
        switch UserDefaults.standard.string(forKey: "NTPalette") {
        case "open": palette = .open
        case "text": palette = .text
        case "new": palette = .new
        default: break
        }
    }

    /// prepare reads the repository's index and makes the editor; false, with the problem on
    /// screen, when nt cannot.
    func prepare() async -> Bool {
        guard let nt else {
            phase = .problem("nt is not installed. Install it with brew install w4jnl/tap/nt, or set NT_BIN to its path.")
            return false
        }
        do {
            try await reindex(nt)
        } catch {
            phase = .problem(error.localizedDescription)
            return false
        }
        if editor == nil {
            editor = NoteEditor(workspace: self)
            editor?.zoom(textSize.rawValue)
        }
        phase = .ready
        return true
    }

    func reindex(_ nt: NT) async throws {
        let ix = try await nt.json(RepoIndex.self, ["_editor", "index"])
        index = ix
        tree = SidebarTree.build(ix, thisYear: String(ix.day.prefix(4)))
        status = SyncStatus.read(stateDir: ix.state)
        reportCache = [:]
        journalDays = Set(ix.notes.compactMap { n -> String? in
            guard n.path.hasPrefix(ix.folders.daily + "/") else { return nil }
            let name = (n.path as NSString).lastPathComponent
            return name.wholeMatch(of: /\d{4}-\d{2}-\d{2}\.md/) != nil ? String(name.prefix(10)) : nil
        })
        await loadTodos()
        if let n = note {
            let back = backlinks(n.path)
            if back != n.backlinks {
                note?.backlinks = back
                editor?.setBacklinks(back)
            }
        }
    }

    // MARK: Opening notes

    func select(_ sel: Selection?) {
        guard let sel, sel != selection else { return }
        switch sel {
        case .today: Task { await openToday() }
        case .weekly: Task { await openWeekly() }
        case .note(let path): show(path)
        case .folder: selection = sel
        case .todos, .calendar, .agents:
            Task {
                await editor?.save()
                selection = sel
            }
        }
    }

    /// weeklyPath is the newest weekly digest, which Weekly opens.
    var weeklyPath: String? {
        index.flatMap { Agenda.latestWeekly($0.notes.map(\.path), folder: $0.folders.weekly) }
    }

    /// openWeekly opens the newest weekly digest, read-only; without one, Weekly says how one
    /// is made.
    func openWeekly() async {
        guard let path = weeklyPath else {
            await editor?.save()
            selection = .weekly
            return
        }
        await open(path)
    }

    private func selectionFor(_ path: String) -> Selection {
        path == todayPath ? .today : path == weeklyPath ? .weekly : .note(path)
    }

    func openToday() async {
        if let p = await todayNote() { show(p) }
    }

    /// goToday goes to today's journal, as a note the person asked for.
    func goToday() async {
        if let p = await todayNote() { go(p) }
    }

    /// todayNote is today's journal, which nt makes when it is not there yet.
    private func todayNote() async -> String? {
        guard let nt else { return nil }
        struct Today: Decodable { let rel: String }
        do {
            todayPath = try await nt.json(Today.self, ["t", "--json"]).rel
            return todayPath
        } catch {
            say(error.localizedDescription)
            return nil
        }
    }

    /// show puts the note at path on screen, scrolled to a heading's anchor or to a line; end
    /// puts the cursor at its end, for a note just made. The note on screen is saved first.
    func show(_ path: String, anchor: String = "", line: Int = 0, end: Bool = false, reload: Bool = false, find: String = "") {
        Task { await open(path, anchor: anchor, line: line, end: end, reload: reload, find: find) }
    }

    /// go shows a note the person asked for: a link followed, a todo's note, a day's journal.
    /// findCount is what the find bar says beside its field.
    var findCount: String {
        if findText.isEmpty { return "" }
        return findOf == 0 ? "no match" : "\(findAt) of \(findOf)"
    }

    /// openFind shows the find bar, its field with the keyboard.
    func openFind() {
        finding = true
        findFocus += 1
    }

    func findInNote(_ words: String) { editor?.find(words) }

    func findStep(_ dir: Int) { editor?.findStep(dir) }

    /// closeFind puts the bar away and takes the marks off the note.
    func closeFind() {
        finding = false
        findText = ""
        findAt = 0
        findOf = 0
        editor?.find("")
    }

    func go(_ path: String, anchor: String = "", line: Int = 0, find: String = "") {
        if let navigate { navigate(path, anchor, line, false, find) } else { show(path, anchor: anchor, line: line, find: find) }
    }

    /// followed opens the note a link, or a "Linked from" line, points at, the note on screen
    /// remembered first so Back returns to it. On the iPhone the stack remembers instead.
    func followed(_ path: String, anchor: String = "") {
        Task {
            if navigate == nil, let n = note, let editor {
                history = Self.push(Visit(path: n.path, top: await editor.top()), on: history)
            }
            go(path, anchor: anchor)
        }
    }

    /// push puts v last in the history, at most max kept.
    nonisolated static func push(_ v: Visit, on list: [Visit], max: Int = historyMax) -> [Visit] {
        Array((list + [v]).suffix(max))
    }

    /// back shows the note a link was followed from, scrolled as it was; a note gone since is
    /// skipped.
    func back() async {
        while let v = history.popLast() {
            if let url = file(v.path), FileManager.default.fileExists(atPath: url.path) {
                await open(v.path, top: v.top)
                return
            }
        }
        say("No note to go back to")
    }

    /// find is a search's words, marked in the note (the editor page's findField); top is how
    /// far it was scrolled, for Back.
    func open(_ path: String, anchor: String = "", line: Int = 0, end: Bool = false, reload: Bool = false, find: String = "", top: Double = 0) async {
        guard let editor, let url = file(path) else { return }
        opening += 1
        let mine = opening
        if path == note?.path, !reload {
            if !anchor.isEmpty { editor.scroll(to: anchor) } else if line > 0 { editor.go(to: line) }
            selection = selectionFor(path)
            return
        }
        guard await editor.save() else {
            say("\(title(note?.path ?? path)) is not saved, so it stays open")
            return
        }
        guard mine == opening else { return } // another note was asked for while this one waited
        guard let data = try? Data(contentsOf: url), let text = String(data: data, encoding: .utf8) else {
            say("\(path) cannot be read: is it still there?")
            return
        }
        let was = outside
        let n = OpenNote(path: path, sha: sha256(data), readOnly: Self.readOnly(text), backlinks: backlinks(path))
        note = n
        if outside { // a file from Finder: the note alone, the sidebar back with the next note from the repository
            outsideTitle = Self.heading(text) ?? ((path as NSString).lastPathComponent as NSString).deletingPathExtension
            if !was {
                sidebarBeforeOutside = sidebar
                sidebar = false
            }
        } else if was {
            sidebar = sidebarBeforeOutside
        }
        if finding { closeFind() } // another note: the bar goes with the one it was for
        editor.load(n, text: text, anchor: anchor, line: line, end: end, find: find, top: top)
        selection = selectionFor(path)
        if !outside { recent = Self.remember(path, in: recent) } // the folders stay as they are: only the person opens one
    }

    /// openFile opens a markdown file by its path on disk, as Finder, the Dock or `open -a nt`
    /// give it: the note it is in the repository, else the file alone, by its full path, with
    /// the sidebar hidden. Before the repository is ready the file waits, and opens in place of
    /// today.
    func openFile(_ url: URL) async {
        guard phase == .ready, let root else {
            askedFile = url
            return
        }
        let path = Self.relative(url, in: root) ?? url.standardizedFileURL.path
        guard path.lowercased().hasSuffix(".md") else {
            say("\(url.lastPathComponent) is not a markdown file")
            return
        }
        await open(path)
    }

    /// heading is a note's H1, the title of a file outside the repository, which the index does
    /// not know; nil without one.
    nonisolated static func heading(_ text: String) -> String? {
        var inFront = false
        for (i, line) in text.split(separator: "\n", omittingEmptySubsequences: false).enumerated() {
            let l = line.trimmingCharacters(in: .whitespaces)
            if l == "---" && (i == 0 || inFront) {
                inFront.toggle()
                continue
            }
            if inFront { continue }
            if l.hasPrefix("# ") { return String(l.dropFirst(2)).trimmingCharacters(in: .whitespaces) }
        }
        return nil
    }

    /// relative is url's path inside root, or nil when it is not under it. Both are resolved
    /// first, so a link on the way (/tmp to /private/tmp, a repository behind a symlink) does
    /// not hide a note.
    nonisolated static func relative(_ url: URL, in root: URL) -> String? {
        let file = url.standardizedFileURL.resolvingSymlinksInPath().path
        let dir = root.standardizedFileURL.resolvingSymlinksInPath().path
        guard file.hasPrefix(dir + "/") else { return nil }
        return String(file.dropFirst(dir.count + 1))
    }

    /// readOnly says whether a note is a digest, the day's or the week's, which nt writes again
    /// whenever it changes, so an edit would not last.
    nonisolated static func readOnly(_ text: String) -> Bool {
        guard text.hasPrefix("---\n") || text.hasPrefix("---\r\n") else { return false }
        for line in text.split(separator: "\n", omittingEmptySubsequences: false).dropFirst() {
            let l = line.trimmingCharacters(in: .whitespaces)
            if l == "---" { break }
            if l == "type: digest" || l == "type: weekly" { return true }
        }
        return false
    }

    /// saved: the editor's text for path is on disk, as sha.
    func saved(_ path: String, sha: String) {
        if note?.path == path { note?.sha = sha }
    }

    func title(_ path: String) -> String {
        if path.hasPrefix("/") { return path == note?.path ? outsideTitle : (path as NSString).lastPathComponent }
        return index?.title(path) ?? (path as NSString).lastPathComponent
    }

    /// day is the day as nt counts it (day_starts), for a todo's done: date.
    func day() async -> String {
        if let nt, let out = try? await nt.run(["_editor", "day"]), out.status == 0 {
            let d = String(decoding: out.stdout, as: UTF8.self).trimmingCharacters(in: .whitespacesAndNewlines)
            if !d.isEmpty { return d }
        }
        return index?.day ?? ""
    }

    func backlinks(_ path: String) -> [Backlink] {
        guard let ix = index else { return [] }
        return (ix.back[path] ?? []).map { from in
            let dir = (from as NSString).deletingLastPathComponent
            return Backlink(path: from, title: ix.title(from), folder: dir.isEmpty ? "/" : dir)
        }
    }

    /// changedLine is "changed 2h ago · macbook" for a note git's history knows: when it last
    /// changed and the device that synced it; nil before its first sync.
    func changedLine(_ path: String) -> String? {
        guard let n = index?.notes.first(where: { $0.path == path }), let at = n.changed else { return nil }
        return Self.changedWords(at: at, by: n.by, now: Date())
    }

    /// changedWords words a change as the terminal does: just now, then minutes and hours up to
    /// two days, then the date, with the host after a middle dot when nt made the commit.
    nonisolated static func changedWords(at: String, by: String?, now: Date) -> String? {
        guard let t = ISO8601DateFormatter().date(from: at) else { return nil }
        let since = now.timeIntervalSince(t)
        var when: String
        if since >= 0 && since < 60 {
            when = "just now"
        } else if since >= 0 && since < 48 * 3600 {
            when = Badge.ago(since)
        } else {
            let cal = Calendar.current
            if cal.isDateInToday(t) {
                when = "today"
            } else if cal.isDateInYesterday(t) {
                when = "yesterday"
            } else {
                let f = DateFormatter()
                f.locale = Locale(identifier: "en_US_POSIX")
                f.dateFormat = cal.component(.year, from: t) == cal.component(.year, from: now) ? "d MMM" : "d MMM yyyy"
                when = f.string(from: t).lowercased()
            }
        }
        if let by, !by.isEmpty { return "changed \(when) · \(by)" }
        return "changed \(when)"
    }

    /// follow follows a link the person clicked in the note on screen.
    func follow(_ href: String) {
        guard let n = note else { return }
        let target = Links.target(from: n.path, href) { FileManager.default.fileExists(atPath: file($0)?.path ?? "") }
        switch target {
        case .note(let path, let anchor):
            if path == n.path, !anchor.isEmpty {
                scroll(to: anchor)
            } else {
                followed(path, anchor: anchor)
            }
        case .anchor(let a): scroll(to: a)
        #if os(macOS)
        case .file(let path): if let u = file(path) { NSWorkspace.shared.open(u) }
        case .web(let url): NSWorkspace.shared.open(url)
        #else
        case .file(let path): preview = file(path)
        case .web(let url): UIApplication.shared.open(url)
        #endif
        case .missing(let path): say("\(path) is not in the repository")
        case .invalid: say("\(href) is not a link nt can follow")
        }
    }

    func scroll(to anchor: String) {
        editor?.scroll(to: anchor)
    }

    // MARK: Todos, agents and journals

    func loadTodos() async {
        guard let nt, let list = try? await nt.json(Todo.List.self, ["todo", "--all", "--json"]) else { return }
        if list.todos != todos { todos = list.todos }
    }

    /// toggle checks a todo, adding done:, or opens it again, through nt.
    func toggle(_ t: Todo) async {
        await setDone(t, !t.done)
    }

    /// setDone checks a todo (done) or opens it again, through nt.
    func setDone(_ t: Todo, _ done: Bool) async {
        await todo([done ? "done" : "undo", t.id])
    }

    /// todosOn says whether a note's task lines are todos, read from the file as the menu asks.
    func todosOn(_ path: String) -> Bool {
        guard let url = file(path), let text = try? String(contentsOf: url, encoding: .utf8) else { return false }
        return Todo.enabled(path, text)
    }

    /// setTodos makes a note's task lines todos, or a checklist again, through nt todo on|off,
    /// which writes `todos:` in its frontmatter (docs/format.md §12).
    @discardableResult
    func setTodos(_ path: String, _ on: Bool) async -> Bool {
        await todo([on ? "on" : "off", path])
    }

    /// setDue sets a todo's due date from words: fri, +3d, 2026-11-03; none clears it.
    func setDue(_ t: Todo, _ when: String) async {
        await todo(["due", t.id, when])
    }

    /// find searches for what a note asked, a tag in its frontmatter (#homelab): in the palette
    /// on the Mac, in the home list's search on iPhone and iPad, the iPhone's screens closed down
    /// to it.
    func find(_ query: String) {
        searchAsked = query
        #if os(macOS)
        palette = .text
        #else
        home?()
        #endif
    }

    /// addTodo adds a todo to the root's todo.md, or a folder's; due:fri in the text sets its
    /// due date.
    func addTodo(_ text: String, in folder: String = "") async -> Bool {
        await todo(["add"] + (folder.isEmpty ? [] : ["--in", folder]) + ["--", text])
    }

    #if !os(macOS)
    /// wrote: nt wrote to the clone (a todo ticked or added, a line captured). The app reads the
    /// notes again, the note on screen too, and half a minute later a sync follows, as after a
    /// save; the Mac has its watcher and nt's sync timer for this.
    func wrote() async {
        if let nt { try? await reindex(nt) }
        await reloadIfChanged()
        syncSoon?.cancel()
        syncSoon = Task {
            try? await Task.sleep(for: .seconds(30))
            guard !Task.isCancelled else { return }
            await syncNow()
        }
    }
    #endif

    @discardableResult
    private func todo(_ args: [String]) async -> Bool {
        guard let nt else { return false }
        await editor?.save() // the note on screen may hold the todo
        var ok = false
        do {
            let out = try await nt.run(["todo"] + args + ["--json"])
            ok = out.status == 0
            if !ok { say(NTError.message(out.stderr)) }
            #if !os(macOS)
            if ok { await wrote() }
            #endif
        } catch {
            say(error.localizedDescription)
        }
        await loadTodos()
        return ok
    }

    /// reports are a day's agent reports, read from their frontmatter, the latest session first.
    func reports(on day: String) -> [AgentReport] {
        if let r = reportCache[day] { return r }
        guard let root, let ix = index, let p = Agenda.parts(day) else { return [] }
        let dir = "\(ix.folders.agents)/\(String(format: "%04d", p.year))/\(day)"
        let names = (try? FileManager.default.contentsOfDirectory(atPath: root.appending(path: dir).path)) ?? []
        var out: [AgentReport] = []
        for name in names where name.hasSuffix(".md") && name != "README.md" && !name.hasPrefix(".") && !name.contains(".conflict-") {
            let rel = dir + "/" + name
            guard let text = try? String(contentsOf: root.appending(path: rel), encoding: .utf8),
                  let r = AgentReport.parse(text, path: rel) else { continue }
            out.append(r)
        }
        let began = Dictionary(out.map { ($0.path, Agenda.instant($0.created) ?? .distantPast) }, uniquingKeysWith: { a, _ in a })
        out.sort { a, b in
            let da = began[a.path] ?? .distantPast, db = began[b.path] ?? .distantPast
            return da != db ? da > db : a.path > b.path
        }
        reportCache[day] = out
        return out
    }

    /// agentDays are the days with agent reports, newest first.
